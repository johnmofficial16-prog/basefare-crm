// A payslip on Trio's letterhead (the same sheet as letters), plus the
// line-by-line "Why?" list used in the apps. The data is frozen when payroll
// is locked, so a payslip never changes afterwards.

import { html } from './dom.js';
import { letterSheet } from './letter.js';
import * as f from './fmt.js';

const ONES = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Eleven', 'Twelve', 'Thirteen',
  'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
const TENS = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];

function below100(n) { return n < 20 ? ONES[n] : TENS[Math.floor(n / 10)] + (n % 10 ? ' ' + ONES[n % 10] : ''); }
function below1000(n) { return (n >= 100 ? ONES[Math.floor(n / 100)] + ' Hundred' + (n % 100 ? ' ' : '') : '') + (n % 100 ? below100(n % 100) : ''); }

/** 125430 → "One Lakh Twenty Five Thousand Four Hundred Thirty" (Indian grouping). */
export function inWords(n) {
  n = Math.round(Math.abs(Number(n) || 0));
  if (!n) return 'Zero';
  const parts = [];
  for (const [size, name] of [[10000000, 'Crore'], [100000, 'Lakh'], [1000, 'Thousand']]) {
    if (n >= size) { parts.push(`${size === 10000000 && n >= 1000000000 ? inWords(Math.floor(n / size)) : below1000(Math.floor(n / size))} ${name}`); n %= size; }
  }
  if (n) parts.push(below1000(n));
  return parts.join(' ');
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
/** "2026-11-06" → "6 November 2026" */
export function longDate(s) {
  if (!s) return '';
  const [y, m, d] = String(s).slice(0, 10).split('-').map(Number);
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

export const slipTitle = (p) => (p.kind === 'settlement' ? `Full and final settlement · ${p.month_name}` : `Payslip for ${p.month_name}`);
export const REGIME = { new: 'New tax regime', old: 'Old tax regime' };

/** The A4 sheet. `p` is the payslip as the API returns it. */
export function payslipSheet(p, { qr = true } = {}) {
  const person = p.person || {};
  const days = `${f.bal(p.paid_days)} of ${p.days_in_month}`;
  const rows = Math.max(p.earnings.length, p.deductions.length);
  const body = html`
    <dl class="slip__who">
      <div><dt>Employee</dt><dd>${person.name}</dd></div>
      <div><dt>Employee code</dt><dd>${person.code || '—'}</dd></div>
      <div><dt>Designation</dt><dd>${person.designation || '—'}</dd></div>
      <div><dt>Centre</dt><dd>${person.centre || '—'}</dd></div>
      <div><dt>Date joined</dt><dd>${person.joined ? longDate(person.joined) : '—'}</dd></div>
      <div><dt>PAN</dt><dd>${person.pan || 'Not given'}</dd></div>
      <div><dt>Paid days</dt><dd>${days}${p.unpaid_days > 0 ? ` (${f.bal(p.unpaid_days)} unpaid)` : ''}</dd></div>
      <div><dt>Monthly salary</dt><dd>${f.rupees(p.rate)}</dd></div>
      <div><dt>Paid to</dt><dd>${p.bank ? `Bank account ${p.bank}` : '—'}</dd></div>
    </dl>
    <table class="slip__t">
      <thead><tr><th>Earnings</th><th class="n">₹</th><th>Deductions</th><th class="n">₹</th></tr></thead>
      <tbody>${Array.from({ length: rows }, (_, i) => {
        const e = p.earnings[i];
        const d = p.deductions[i];
        return html`<tr><td>${e ? e.label : ''}</td><td class="n">${e ? f.num(e.amount) : ''}</td><td>${d ? d.label : ''}</td><td class="n">${d ? f.num(d.amount) : ''}</td></tr>`;
      })}</tbody>
      <tfoot><tr><th>Gross earnings</th><th class="n">${f.num(p.gross)}</th><th>Total deductions</th><th class="n">${f.num(p.total_deductions)}</th></tr></tfoot>
    </table>
    <div class="slip__net"><span>Net pay${p.kind === 'settlement' ? ' (final settlement)' : ''}</span><b>${f.rupees(p.net)}</b>
      <small>Rupees ${inWords(p.net)} only</small></div>
    <p class="slip__note">${REGIME[p.regime] || REGIME.new}. This tax year so far: taxable pay ${f.rupees(p.ytd?.taxable || 0)}, income tax deducted ${f.rupees(p.ytd?.tds || 0)}.
      Each figure is explained line by line in the Trio HR app.</p>`;
  return letterSheet({
    letter: { status: 'issued', subject: slipTitle(p), number: p.number, date: longDate(p.pay_date), verify_url: qr && p.published ? p.verify_url : null, verify_code: p.verify_code },
    letterhead: p.letterhead || {},
  }, { body, qr: qr && p.published, kind: 'payslip', unsigned: 'This payslip is generated by Trio HR and needs no signature.' });
}

/** Earnings and deductions, each with its "Why?" (apps, not the printed sheet). */
export function whyList(items, sign = '') {
  return html`${items.map((x) => html`<details class="why">
    <summary><span>${x.label}</span><b class="tnum">${sign}${f.rupees(x.amount)}</b></summary>
    <p>${x.why || 'No more detail.'}</p></details>`)}`;
}
